"""Generate JSON Schemas and TypeScript protocol types from the Pydantic models (decision D14).

    uv run python tools/codegen.py          # write schemas/*.json and packages/ts/protocol/src/generated/
    uv run python tools/codegen.py --check  # exit 1 if the committed files are stale

Pipeline: `titan_core.protocol` (Pydantic v2, source of truth) -> `schemas/*.json` (JSON Schema
2020-12) -> `packages/ts/protocol/src/generated/protocol.ts` (zod validators and inferred types).
The TypeScript emitter supports exactly the JSON Schema subset Pydantic produces for the
protocol models and fails loudly on anything else.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import GenerateJsonSchema, models_json_schema
from pydantic_core import CoreSchema

from titan_core.protocol import SCHEMA_FILES, SchemaFile

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS_DIR = ROOT / "schemas"
TS_OUT = ROOT / "packages" / "ts" / "protocol" / "src" / "generated" / "protocol.ts"
JSON_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
ID_BASE = "https://titan.local/schemas/"
REF_PREFIX = "#/$defs/"
HEADER = "GENERATED by tools/codegen.py from titan_core.protocol. DO NOT EDIT."

JsonSchema = dict[str, Any]


class TitanSchemaGenerator(GenerateJsonSchema):
    """Pydantic's generator without per-field titles (the spec's schemas have none)."""

    def field_title_should_be_set(self, schema: CoreSchema) -> bool:
        return False


# ---------------------------------------------------------------------------- JSON Schema
def _defs_for(models: Iterable[type[BaseModel]]) -> tuple[dict[type[BaseModel], str], dict[str, JsonSchema]]:
    pairs = [(m, "validation") for m in models]
    keys, top = models_json_schema(
        pairs,  # type: ignore[arg-type]
        ref_template=REF_PREFIX + "{model}",
        schema_generator=TitanSchemaGenerator,
    )
    names = {model: keys[(model, "validation")]["$ref"].removeprefix(REF_PREFIX) for model in dict(pairs)}
    return names, dict(top.get("$defs", {}))


def _rewrite_refs(node: Any, old: str, new: str) -> Any:
    if isinstance(node, dict):
        return {k: (new if k == "$ref" and v == old else _rewrite_refs(v, old, new)) for k, v in node.items()}
    if isinstance(node, list):
        return [_rewrite_refs(v, old, new) for v in node]
    return node


def build_schema_file(spec: SchemaFile) -> tuple[JsonSchema, dict[str, JsonSchema]]:
    """Return the JSON Schema document for one file and every named definition it contains."""
    names, defs = _defs_for(spec.models)
    all_defs = dict(defs)
    doc: JsonSchema = {
        "$schema": JSON_SCHEMA_DIALECT,
        "$id": f"{ID_BASE}{spec.name}.json",
        "title": spec.title,
    }
    if spec.root is not None:
        root_name = names[spec.root]
        root = defs.pop(root_name)
        defs = _rewrite_refs(defs, REF_PREFIX + root_name, "#")
        root = _rewrite_refs(root, REF_PREFIX + root_name, "#")
        doc.update({k: v for k, v in root.items() if k != "title"})
    for keyword, mapping in spec.type_maps.items():
        doc[keyword] = {msg_type: REF_PREFIX + names[model] for msg_type, model in mapping.items()}
    if defs:
        doc["$defs"] = dict(sorted(defs.items()))
    return doc, all_defs


def render_json(doc: JsonSchema) -> str:
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


# ---------------------------------------------------------------------------- TypeScript + zod
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_KNOWN_KEYWORDS = {
    "type",
    "properties",
    "required",
    "additionalProperties",
    "items",
    "enum",
    "const",
    "anyOf",
    "oneOf",
    "discriminator",
    "$ref",
    "format",
    "pattern",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "minItems",
    "maxItems",
    "minLength",
    "maxLength",
    "title",
    "description",
    "default",
}


class UnsupportedSchema(ValueError):
    pass


def _ref_name(ref: str) -> str:
    if not ref.startswith(REF_PREFIX):
        raise UnsupportedSchema(f"unsupported $ref {ref!r}")
    return ref.removeprefix(REF_PREFIX)


def _numeric(base: str, schema: JsonSchema) -> str:
    out = base
    for keyword, method in (
        ("minimum", "gte"),
        ("maximum", "lte"),
        ("exclusiveMinimum", "gt"),
        ("exclusiveMaximum", "lt"),
    ):
        if keyword in schema:
            out += f".{method}({json.dumps(schema[keyword])})"
    return out


def zod_expr(schema: JsonSchema, indent: str = "") -> str:
    unknown = set(schema) - _KNOWN_KEYWORDS
    if unknown:
        raise UnsupportedSchema(f"unsupported keywords {sorted(unknown)} in {schema}")
    if "$ref" in schema:
        return _ref_name(schema["$ref"]) + "Schema"
    if "const" in schema:
        return f"z.literal({json.dumps(schema['const'])})"
    if "enum" in schema:
        values = schema["enum"]
        if all(isinstance(v, str) for v in values):
            return "z.enum([" + ", ".join(json.dumps(v) for v in values) + "])"
        return "z.union([" + ", ".join(f"z.literal({json.dumps(v)})" for v in values) + "])"
    for keyword in ("anyOf", "oneOf"):
        if keyword in schema:
            variants = schema[keyword]
            non_null = [v for v in variants if v != {"type": "null"}]
            nullable = len(non_null) != len(variants)
            if len(non_null) == 1:
                expr = zod_expr(non_null[0], indent)
            elif "discriminator" in schema and not nullable:
                prop = schema["discriminator"]["propertyName"]
                inner = ", ".join(zod_expr(v, indent) for v in non_null)
                expr = f"z.discriminatedUnion({json.dumps(prop)}, [{inner}])"
            else:
                expr = "z.union([" + ", ".join(zod_expr(v, indent) for v in non_null) + "])"
            return expr + (".nullable()" if nullable else "")
    kind = schema.get("type")
    if kind is None:
        return "z.unknown()"
    if kind == "string":
        expr = "z.string()"
        fmt = schema.get("format")
        if fmt == "uuid":
            expr += ".uuid()"
        elif fmt == "date-time":
            expr += ".datetime({ offset: true })"
        elif fmt is not None:
            raise UnsupportedSchema(f"unsupported string format {fmt!r}")
        if "minLength" in schema:
            expr += f".min({schema['minLength']})"
        if "maxLength" in schema:
            expr += f".max({schema['maxLength']})"
        if "pattern" in schema:
            expr += f".regex(new RegExp({json.dumps(schema['pattern'])}))"
        return expr
    if kind == "integer":
        return _numeric("z.number().int()", schema)
    if kind == "number":
        return _numeric("z.number()", schema)
    if kind == "boolean":
        return "z.boolean()"
    if kind == "null":
        return "z.null()"
    if kind == "array":
        expr = f"z.array({zod_expr(schema.get('items', {}), indent)})"
        if "minItems" in schema:
            expr += f".min({schema['minItems']})"
        if "maxItems" in schema:
            expr += f".max({schema['maxItems']})"
        return expr
    if kind == "object":
        props: Mapping[str, JsonSchema] = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        if not props:
            value = zod_expr(extra, indent) if isinstance(extra, dict) and extra else "z.unknown()"
            return f"z.record(z.string(), {value})"
        required = set(schema.get("required", []))
        inner = indent + "  "
        lines = ["z.object({"]
        for name, prop in props.items():
            if "description" in prop:
                lines.append(f"{inner}/** {prop['description']} */")
            key = name if _IDENT.match(name) else json.dumps(name)
            optional = "" if name in required else ".optional()"
            lines.append(f"{inner}{key}: {zod_expr(prop, inner)}{optional},")
        lines.append(indent + "})" + (".strict()" if extra is False else ".passthrough()"))
        return "\n".join(lines)
    raise UnsupportedSchema(f"unsupported type {kind!r}")


def _deps(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                found.add(_ref_name(value))
            else:
                found |= _deps(value)
    elif isinstance(node, list):
        for value in node:
            found |= _deps(value)
    return found


def topo_order(defs: Mapping[str, JsonSchema]) -> list[str]:
    order: list[str] = []
    state: dict[str, int] = {}

    def visit(name: str) -> None:
        if state.get(name) == 2:
            return
        if state.get(name) == 1:
            raise UnsupportedSchema(f"recursive schema through {name}")
        state[name] = 1
        for dep in sorted(_deps(defs[name])):
            visit(dep)
        state[name] = 2
        order.append(name)

    for name in sorted(defs):
        visit(name)
    return order


def render_ts(defs: Mapping[str, JsonSchema], type_maps: Mapping[str, Mapping[str, str]]) -> str:
    out = [f"// {HEADER}", 'import { z } from "zod";', ""]
    for name in topo_order(defs):
        schema = defs[name]
        if "description" in schema:
            out.append("/** " + " ".join(schema["description"].split()) + " */")
        out.append(f"export const {name}Schema = {zod_expr(schema)};")
        out.append(f"export type {name} = z.infer<typeof {name}Schema>;")
        out.append("")
    for const_name, mapping in type_maps.items():
        out.append(f"export const {const_name} = {{")
        for msg_type, ref in mapping.items():
            out.append(f"  {json.dumps(msg_type)}: {_ref_name(ref)}Schema,")
        out.append("} as const;")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


_TS_MAP_NAMES = {
    "x-titan-message-types": "MESSAGE_PAYLOAD_SCHEMAS",
    "x-titan-ws-message-types": "WS_DATA_SCHEMAS",
}


# ---------------------------------------------------------------------------- driver
def generate() -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    merged: dict[str, JsonSchema] = {}
    ts_maps: dict[str, dict[str, str]] = {}
    for spec in SCHEMA_FILES:
        doc, defs = build_schema_file(spec)
        outputs[SCHEMAS_DIR / f"{spec.name}.json"] = render_json(doc)
        for name, schema in defs.items():
            if name in merged and merged[name] != schema:
                raise UnsupportedSchema(f"conflicting definitions for {name}")
            merged[name] = schema
        for keyword, mapping in doc.items():
            if keyword in _TS_MAP_NAMES:
                ts_maps[_TS_MAP_NAMES[keyword]] = mapping
    outputs[TS_OUT] = render_ts(merged, ts_maps)
    return outputs


def stale_files(outputs: Mapping[Path, str]) -> list[Path]:
    return [
        path
        for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args(argv)
    outputs = generate()
    if args.check:
        stale = stale_files(outputs)
        for path in stale:
            print(f"stale: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
        if stale:
            print("Generated protocol files are out of date. Run `pnpm codegen` and commit.", file=sys.stderr)
            return 1
        return 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
